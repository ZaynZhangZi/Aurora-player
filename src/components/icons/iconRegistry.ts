const filled = new WeakMap<IconNode, IconNode>()
export function iconData(name: string, solid = false): IconNode {
  const icon = icons[name] || icons['circle-help']
  if (!solid) return icon
  let result = filled.get(icon)
  if (!result) { result = icon.map(([tag, attrs]) => [tag, {...attrs, fill: 'currentColor'}]) as IconNode; filled.set(icon, result) }
  return result
}
